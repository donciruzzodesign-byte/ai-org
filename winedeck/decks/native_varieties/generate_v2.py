def main():
    total = 0
    for slug, eyebrow, varieties in REGIONS:
        slides = []
        for idx, v in enumerate(varieties, 1):
            (title, name_it, wtype, origin, feature,
             local_name, local_note, jp_name, jp_note) = v
            base = f"{slug}_{idx:02d}"
            slides.append({
                "kind": "profile",
                "wine_type": wtype,
                "eyebrow": eyebrow,
                "name_it": name_it,
                "name_kana": title,
                "grape_photo": f"{PHOTO_REL}/{base}_grape.jpg",
                "origin": origin,
                "feature": feature,
                "local": {"name": local_name, "note": local_note, "photo": f"{PHOTO_REL}/{base}_local.jpg"},
                "jp": {"name": jp_name, "note": jp_note, "photo": f"{PHOTO_REL}/{base}_jp.jpg"},
            })
        deck = {"name": slug, "wine_type": "red", "slides": slides}
        path = os.path.join(HERE, f"{slug}.json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(deck, f, ensure_ascii=False, indent=2)
        total += len(slides)
        print(f"wrote {path} ({len(slides)} slides)")
    print(f"TOTAL slides: {total}")

if __name__ == "__main__":
    main()
