def slugify_ok(s):
    return s

def main():
    total = 0
    for slug, eyebrow, varieties in REGIONS:
        slides = []
        for title, wtype, feature, local_note, jp_note in varieties:
            slides.append({
                "kind": "bullets",
                "wine_type": wtype,
                "eyebrow": eyebrow,
                "title": title,
                "items": [
                    ["特徴", feature],
                    ["現地ペアリング", local_note],
                    ["日本食ペアリング", jp_note],
                ],
            })
        deck = {"name": slug, "wine_type": "red", "slides": slides}
        path = os.path.join(HERE, f"{slug}.json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(deck, f, ensure_ascii=False, indent=2)
        total += len(slides)
        print(f"wrote {path} ({len(slides)} slides)")
    print(f"TOTAL slides: {total}")

if __name__ == "__main__":
    main()
